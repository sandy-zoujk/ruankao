CREATE TABLE sys_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(30) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  nickname VARCHAR(50) NOT NULL,
  role VARCHAR(10) NOT NULL DEFAULT 'USER',
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  token_version INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE study_plan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  title VARCHAR(120) NOT NULL,
  category VARCHAR(50) NOT NULL,
  plan_date DATE NOT NULL,
  duration_minutes INT NOT NULL DEFAULT 60,
  completed BOOLEAN NOT NULL DEFAULT FALSE,
  notes VARCHAR(500),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE knowledge_chapter (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  name VARCHAR(100) NOT NULL,
  category VARCHAR(50) NOT NULL,
  priority INT NOT NULL DEFAULT 3,
  mastery INT NOT NULL DEFAULT 0,
  question_count INT NOT NULL DEFAULT 0,
  correct_count INT NOT NULL DEFAULT 0,
  last_review_date DATE,
  CONSTRAINT uk_chapter_user_name UNIQUE (user_id, name)
);

CREATE TABLE wrong_question (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  title VARCHAR(200) NOT NULL,
  content VARCHAR(4000) NOT NULL,
  correct_answer VARCHAR(4000),
  my_answer VARCHAR(4000),
  error_reason VARCHAR(50) NOT NULL,
  chapter_id BIGINT,
  review_count INT NOT NULL DEFAULT 0,
  mastered BOOLEAN NOT NULL DEFAULT FALSE,
  next_review_date DATE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  source_question_id BIGINT,
  CONSTRAINT uk_wrong_question_source UNIQUE (user_id, source_question_id)
);

CREATE TABLE question_bank (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, question_code VARCHAR(50) UNIQUE NOT NULL,
  chapter VARCHAR(100) NOT NULL, content VARCHAR(4000) NOT NULL, option_a VARCHAR(500) NOT NULL,
  option_b VARCHAR(500) NOT NULL, option_c VARCHAR(500) NOT NULL, option_d VARCHAR(500) NOT NULL,
  correct_option CHAR(1) NOT NULL, explanation VARCHAR(4000), enabled BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE practice_attempt (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL, chapter VARCHAR(100),
  question_count INT NOT NULL, correct_count INT, score DECIMAL(5,2), submitted BOOLEAN DEFAULT FALSE,
  started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, submitted_at TIMESTAMP
);
CREATE TABLE practice_answer (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, attempt_id BIGINT NOT NULL, question_id BIGINT NOT NULL,
  sequence_no INT NOT NULL, selected_option CHAR(1), correct BOOLEAN,
  CONSTRAINT uk_attempt_question UNIQUE (attempt_id, question_id)
);

CREATE TABLE tutorial_source (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source_name VARCHAR(100) NOT NULL,
 source_url VARCHAR(1000) UNIQUE NOT NULL, chapter VARCHAR(100) NOT NULL, enabled BOOLEAN DEFAULT TRUE,
 sync_status VARCHAR(20) DEFAULT 'NEVER', http_status INT, last_error VARCHAR(1000), last_duration_ms BIGINT,
 last_synced_at TIMESTAMP, last_success_at TIMESTAMP, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tutorial_version (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source_id BIGINT NOT NULL, title VARCHAR(300) NOT NULL,
 summary VARCHAR(1000), content_hash CHAR(64) NOT NULL, status VARCHAR(20) DEFAULT 'DRAFT',
 fetched_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, published_at TIMESTAMP, UNIQUE(source_id,content_hash)
);
CREATE TABLE tutorial_section (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version_id BIGINT NOT NULL, section_key VARCHAR(64) NOT NULL,
 title VARCHAR(300) NOT NULL, content_html VARCHAR(20000) NOT NULL, sequence_no INT NOT NULL, UNIQUE(version_id,section_key)
);
CREATE TABLE user_tutorial_progress (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL, source_id BIGINT NOT NULL,
 section_key VARCHAR(64) NOT NULL, completed BOOLEAN DEFAULT TRUE, completed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE(user_id,source_id,section_key)
);
