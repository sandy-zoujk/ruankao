CREATE TABLE sys_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(30) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  nickname VARCHAR(50) NOT NULL,
  role VARCHAR(10) NOT NULL DEFAULT 'USER',
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  token_version INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE study_plan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  title VARCHAR(120) NOT NULL,
  category VARCHAR(50) NOT NULL,
  plan_date DATE NOT NULL,
  duration_minutes INT NOT NULL DEFAULT 60,
  completed BOOLEAN NOT NULL DEFAULT FALSE,
  notes VARCHAR(500),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE knowledge_chapter (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  name VARCHAR(100) NOT NULL,
  category VARCHAR(50) NOT NULL,
  priority INT NOT NULL DEFAULT 3,
  mastery INT NOT NULL DEFAULT 0,
  question_count INT NOT NULL DEFAULT 0,
  correct_count INT NOT NULL DEFAULT 0,
  last_review_date DATE,
  CONSTRAINT uk_chapter_user_name UNIQUE (user_id, name)
);

CREATE TABLE wrong_question (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  title VARCHAR(200) NOT NULL,
  content CLOB NOT NULL,
  correct_answer CLOB,
  my_answer CLOB,
  error_reason VARCHAR(50) NOT NULL,
  chapter_id BIGINT,
  review_count INT NOT NULL DEFAULT 0,
  mastered BOOLEAN NOT NULL DEFAULT FALSE,
  next_review_date DATE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_wrong_question_chapter FOREIGN KEY (chapter_id)
    REFERENCES knowledge_chapter(id) ON DELETE SET NULL
);
